USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS ATMOSYNC_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS ATMOSYNC;
CREATE SCHEMA IF NOT EXISTS ATMOSYNC.RAW;
CREATE SCHEMA IF NOT EXISTS ATMOSYNC.STAGING;
CREATE SCHEMA IF NOT EXISTS ATMOSYNC.MARTS;

USE WAREHOUSE ATMOSYNC_WH;
USE SCHEMA ATMOSYNC.RAW;

-- Raw IoT events: full JSON stored as-is (ELT style)
CREATE TABLE IF NOT EXISTS RAW_CONTAINER_TELEMETRY (
  EVENT_PAYLOAD   VARIANT,
  KAFKA_TOPIC     STRING,
  KAFKA_PARTITION NUMBER,
  KAFKA_OFFSET    NUMBER,
  INGESTED_AT     TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Mock commodity price table (per market)
CREATE TABLE IF NOT EXISTS RAW_COMMODITY_PRICES (
  COMMODITY    STRING,
  MARKET_NAME  STRING,
  MARKET_LAT   FLOAT,
  MARKET_LON   FLOAT,
  PRICE_PER_KG FLOAT,
  PRICE_DATE   DATE
);