USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS ATMOSYNC_READER;

GRANT USAGE ON WAREHOUSE ATMOSYNC_WH TO ROLE ATMOSYNC_READER;
GRANT USAGE ON DATABASE ATMOSYNC TO ROLE ATMOSYNC_READER;

GRANT USAGE ON SCHEMA ATMOSYNC.RAW     TO ROLE ATMOSYNC_READER;
GRANT USAGE ON SCHEMA ATMOSYNC.STAGING TO ROLE ATMOSYNC_READER;
GRANT USAGE ON SCHEMA ATMOSYNC.MARTS   TO ROLE ATMOSYNC_READER;

GRANT SELECT ON ALL TABLES IN SCHEMA ATMOSYNC.RAW     TO ROLE ATMOSYNC_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA ATMOSYNC.MARTS   TO ROLE ATMOSYNC_READER;
GRANT SELECT ON ALL VIEWS  IN SCHEMA ATMOSYNC.STAGING TO ROLE ATMOSYNC_READER;
GRANT SELECT ON ALL VIEWS  IN SCHEMA ATMOSYNC.MARTS   TO ROLE ATMOSYNC_READER;

GRANT SELECT ON FUTURE TABLES IN SCHEMA ATMOSYNC.RAW     TO ROLE ATMOSYNC_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ATMOSYNC.MARTS   TO ROLE ATMOSYNC_READER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA ATMOSYNC.STAGING TO ROLE ATMOSYNC_READER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA ATMOSYNC.MARTS   TO ROLE ATMOSYNC_READER;

CREATE USER IF NOT EXISTS SUPERSET_SVC
  PASSWORD = 'CHANGE_ME_STRONG_PASSWORD'
  TYPE = LEGACY_SERVICE
  DEFAULT_ROLE = ATMOSYNC_READER
  DEFAULT_WAREHOUSE = ATMOSYNC_WH
  MUST_CHANGE_PASSWORD = FALSE;

GRANT ROLE ATMOSYNC_READER TO USER SUPERSET_SVC;

SHOW GRANTS TO ROLE ATMOSYNC_READER;