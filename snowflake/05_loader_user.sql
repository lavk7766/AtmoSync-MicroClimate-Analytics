USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS ATMOSYNC_LOADER;

GRANT USAGE ON WAREHOUSE ATMOSYNC_WH TO ROLE ATMOSYNC_LOADER;
GRANT USAGE ON DATABASE ATMOSYNC TO ROLE ATMOSYNC_LOADER;
GRANT USAGE ON SCHEMA ATMOSYNC.RAW TO ROLE ATMOSYNC_LOADER;

GRANT SELECT, INSERT ON ALL TABLES IN SCHEMA ATMOSYNC.RAW TO ROLE ATMOSYNC_LOADER;
GRANT SELECT, INSERT ON FUTURE TABLES IN SCHEMA ATMOSYNC.RAW TO ROLE ATMOSYNC_LOADER;

CREATE USER IF NOT EXISTS LOADER_SVC
  PASSWORD = 'CHANGE_ME_STRONG_PASSWORD'
  TYPE = LEGACY_SERVICE
  DEFAULT_ROLE = ATMOSYNC_LOADER
  DEFAULT_WAREHOUSE = ATMOSYNC_WH
  MUST_CHANGE_PASSWORD = FALSE;

GRANT ROLE ATMOSYNC_LOADER TO USER LOADER_SVC;