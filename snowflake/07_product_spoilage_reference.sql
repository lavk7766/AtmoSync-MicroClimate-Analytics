USE ROLE ACCOUNTADMIN;
USE WAREHOUSE ATMOSYNC_WH;
USE SCHEMA ATMOSYNC.RAW;

CREATE TABLE IF NOT EXISTS PRODUCT_SPOILAGE_REFERENCE (
  PRODUCT_NAME             STRING,
  PRODUCT_STAGE_OR_VARIETY STRING,
  RECOMMENDED_TEMP_MIN_C   FLOAT,
  RECOMMENDED_TEMP_MAX_C   FLOAT,
  BEST_TEMP_C              FLOAT,
  HUMIDITY_MIN_PCT         FLOAT,
  HUMIDITY_MAX_PCT         FLOAT,
  SHELF_LIFE_MIN_HOURS     FLOAT,
  SHELF_LIFE_MAX_HOURS     FLOAT,
  DATA_SOURCE              STRING,
  SOURCE_URL               STRING,
  NOTES                    STRING,
  LOADED_AT                TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- The loader reloads this table on each run, so it needs DELETE on this table only
GRANT SELECT, INSERT, DELETE ON TABLE ATMOSYNC.RAW.PRODUCT_SPOILAGE_REFERENCE TO ROLE ATMOSYNC_LOADER;

SHOW TABLES LIKE 'PRODUCT_SPOILAGE_REFERENCE' IN SCHEMA ATMOSYNC.RAW;