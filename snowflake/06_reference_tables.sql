USE ROLE ACCOUNTADMIN;
USE WAREHOUSE ATMOSYNC_WH;
USE SCHEMA ATMOSYNC.RAW;

-- Data dictionary section 3: container metadata
CREATE TABLE IF NOT EXISTS RAW_CONTAINER_METADATA (
  CONTAINER_ID   STRING,
  PRODUCT_NAME   STRING,
  QUANTITY       FLOAT,
  QUANTITY_UNIT  STRING,
  ORIGIN         STRING,
  DESTINATION    STRING,
  BATCH_ID       STRING,
  SOURCE_TYPE    STRING,
  INGESTED_AT    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Data dictionary section 4: commodity pricing
CREATE TABLE IF NOT EXISTS RAW_MARKET_PRICES (
  PRODUCT_NAME    STRING,
  MARKET_NAME     STRING,
  PRICE           FLOAT,
  CURRENCY        STRING,
  PRICE_TIMESTAMP TIMESTAMP_TZ,
  SOURCE_TYPE     STRING,
  INGESTED_AT     TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Data dictionary section 5: route information
CREATE TABLE IF NOT EXISTS RAW_ROUTE_INFO (
  ORIGIN                  STRING,
  DESTINATION             STRING,
  DISTANCE_KM             FLOAT,
  ESTIMATED_TRAVEL_HOURS  FLOAT,
  TRANSPORT_COST          FLOAT,
  CURRENCY                STRING,
  SOURCE_TYPE             STRING,
  INGESTED_AT             TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

